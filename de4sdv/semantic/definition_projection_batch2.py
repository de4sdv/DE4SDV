class _Source:
    """One model file: original text, a structure mask and its comment spans.

    The mask blanks comment interiors and both quoted-token forms (double
    quoted strings and single-quoted unrestricted names) with spaces, keeping
    offsets and newlines, so braces, semicolons or keywords inside comments or
    quoted tokens can never move a declaration boundary or supply code.
    """

    def __init__(self, relative: str, text: str) -> None:
        self.relative = relative
        self.text = text
        out: list[str] = []
        self.comments: list[tuple[int, int, str]] = []
        index = 0
        length = len(text)
        while index < length:
            if text.startswith("/*", index):
                end = text.find("*/", index + 2)
                if end == -1:
                    raise DefinitionBatch2Error(f"{relative}: unterminated comment")
                self.comments.append((index, end + 2, text[index + 2:end]))
                out.append("".join("\n" if c == "\n" else " " for c in text[index:end + 2]))
                index = end + 2
                continue
            if text.startswith("//", index):
                end = text.find("\n", index)
                end = length if end == -1 else end
                out.append(" " * (end - index))
                index = end
                continue
            char = text[index]
            if char in ('"', "'"):
                start = index
                index += 1
                while index < length:
                    if text[index] == "\\":
                        index += 2
                    elif text[index] == char:
                        index += 1
                        break
                    else:
                        index += 1
                else:
                    raise DefinitionBatch2Error(f"{relative}: unterminated quoted token")
                out.append(char + " " * (index - start - 2) + char)
                continue
            out.append(char)
            index += 1
        self.mask = "".join(out)
        depth = 0
        self.depth: list[int] = []
        for char in self.mask:
            self.depth.append(depth)
            depth += (char == "{") - (char == "}")
        if depth != 0:
            raise DefinitionBatch2Error(f"{relative}: unbalanced braces")

    # -- blocks ------------------------------------------------------------
    def _braced(self, header_end: int, label: str) -> tuple[int, int]:
        index = header_end
        while index < len(self.mask) and self.mask[index] not in "{;":
            index += 1
        if index >= len(self.mask) or self.mask[index] == ";":
            raise DefinitionBatch2Error(f"{self.relative}: {label} has no owned body")
        open_index = index
        target = self.depth[open_index]
        for close in range(open_index + 1, len(self.mask)):
            if self.mask[close] == "}" and self.depth[close] == target + 1:
                return open_index, close
        raise DefinitionBatch2Error(f"{self.relative}: {label} body is unterminated")

    def _unique(self, pattern: str, label: str, span: tuple[int, int] | None = None,
                direct: bool = False) -> re.Match[str]:
        start, end = span if span else (0, len(self.mask))
        base = self.depth[start] + 1 if span else 0
        matches = [
            match for match in re.finditer(pattern, self.mask[start:end])
            if not direct or self.depth[start + match.start()] == base
        ]
        if not matches:
            raise DefinitionBatch2Error(f"{self.relative}: {label} not found")
        if len(matches) > 1:
            raise DefinitionBatch2Error(f"{self.relative}: {label} is ambiguous ({len(matches)} live matches)")
        return matches[0]

    def owner_block(self, owner: str) -> tuple[int, int]:
        """Exactly one live ``package X`` or ``<kind> def X`` block."""
        package = _PACKAGE_OWNER.match(owner)
        if package:
            pattern = r"\bpackage\s+" + re.escape(package["name"]) + r"(?=\s*\{)"
        else:
            definition = _DEF_OWNER.match(owner)
            if not definition:
                raise DefinitionBatch2Error(f"{self.relative}: unsupported owner form {owner!r}")
            pattern = (r"(?m)^[ \t]*(?:(?:public|private|protected)\s+)?(?:abstract\s+)?"
                       + re.escape(definition["kind"]) + r"\s+def\s+"
                       + re.escape(definition["name"]) + r"\b")
        match = self._unique(pattern, owner)
        return self._braced(match.end(), owner)

    def defines(self, name: str) -> bool:
        return re.search(r"\bdef\s+" + re.escape(name) + r"\b", self.mask) is not None

    def names_documentation(self, name: str) -> bool:
        return re.search(r"\bdoc\s+" + re.escape(name) + r"\b", self.mask) is not None

    # -- annotations ---------------------------------------------------------
    def direct_annotations(self, block: tuple[int, int]) -> list[dict[str, Any]]:
        """Documentation and named comments at the block body's direct depth."""
        open_index, close = block
        base = self.depth[open_index] + 1
        found: list[dict[str, Any]] = []
        previous_end = open_index + 1
        for start, end, body in self.comments:
            if start <= open_index or end > close:
                continue
            if self.depth[start] != base:
                previous_end = max(previous_end, end)
                continue
            segment = self.mask[previous_end:start]
            cut = max(segment.rfind(";"), segment.rfind("{"), segment.rfind("}"))
            prefix = " ".join(segment[cut + 1:].split())
            previous_end = end
            doc = re.fullmatch(r"(?:(?:public|private|protected)\s+)?doc(?:\s+([A-Za-z_]\w*))?", prefix)
            if doc:
                found.append({"kind": "doc", "name": doc[1], "about": None, "body": body})
                continue
            comment = re.fullmatch(
                r"(?:(?:public|private|protected)\s+)?comment\s+(?!about\b)([A-Za-z_]\w*)"
                r"(?:\s+about\s+(.+))?",
                prefix,
            )
            if comment:
                about = [item.strip() for item in comment[2].split(",")] if comment[2] else []
                found.append({"kind": "comment", "name": comment[1], "about": about, "body": body})
        return found

    # -- records -------------------------------------------------------------
    def direct_record_usages(self, block: tuple[int, int], record_type: str) -> dict[str, tuple[int, int]]:
        open_index, close = block
        base = self.depth[open_index] + 1
        usages: dict[str, tuple[int, int]] = {}
        pattern = r"\bpart\s+([A-Za-z_]\w*)\s*:\s*" + re.escape(record_type) + r"\s*(?=\{)"
        for match in re.finditer(pattern, self.mask[open_index:close]):
            position = open_index + match.start()
            if self.depth[position] != base:
                continue
            name = match[1]
            if name in usages:
                raise DefinitionBatch2Error(f"{self.relative}: duplicate record usage {name!r}")
            usages[name] = self._braced(open_index + match.end(), f"record {name}")
        return usages

    def record_fields(self, block: tuple[int, int], fields: tuple[str, ...], label: str) -> dict[str, str]:
        open_index, close = block
        base = self.depth[open_index] + 1
        values: dict[str, str] = {}
        for match in re.finditer(r"\battribute\s*:>>\s*([A-Za-z_]\w*)\s*=\s*", self.mask[open_index:close]):
            position = open_index + match.start()
            if self.depth[position] != base:
                continue
            key = match[1]
            value_start = open_index + match.end()
            if self.text[value_start:value_start + 1] != '"':
                raise DefinitionBatch2Error(f"{self.relative}: {label}.{key} is not a String literal")
            value_end = value_start + 1
            while self.text[value_end] != '"':
                value_end += 2 if self.text[value_end] == "\\" else 1
            rest = self.mask[value_end + 1:close].lstrip()
            if not rest.startswith(";"):
                raise DefinitionBatch2Error(f"{self.relative}: {label}.{key} is not a single literal")
            if key in values:
                raise DefinitionBatch2Error(f"{self.relative}: {label}.{key} is assigned twice")
            values[key] = self.text[value_start + 1:value_end]
        if set(values) != set(fields):
            raise DefinitionBatch2Error(
                f"{self.relative}: {label} fields {sorted(values)} != {sorted(fields)}"
            )
        return values

    def carrier_ends(self, declaration: str) -> list[dict[str, str]]:
        block = self.owner_block(declaration)
        open_index, close = block
        base = self.depth[open_index] + 1
        ends = []
        for match in re.finditer(r"\bend\s+([A-Za-z_]\w*)\s*:\s*([A-Za-z_][\w:]*)\s*;", self.mask[open_index:close]):
            if self.depth[open_index + match.start()] == base:
                ends.append({"name": match[1], "type": match[2]})
        if len(ends) != 2:
            raise DefinitionBatch2Error(f"{self.relative}: {declaration} must own exactly two typed ends")
        return ends

    def specializes(self, declaration: str, target: str) -> bool:
        definition = _DEF_OWNER.match(declaration)
        if not definition:
            return False
        pattern = (r"(?m)^[ \t]*(?:(?:public|private|protected)\s+)?(?:abstract\s+)?"
                   + re.escape(definition["kind"]) + r"\s+def\s+"
                   + re.escape(definition["name"]) + r"\b")
        match = self._unique(pattern, declaration)
        header_end = match.end()
        while header_end < len(self.mask) and self.mask[header_end] not in "{;":
            header_end += 1
        header = self.mask[match.end():header_end]
        special = re.match(r"\s*(?::>|\bspecializes\b)\s*(.+)$", header, re.S)
        if not special:
            return False
        names = {item.strip().split("::")[-1] for item in special[1].split(",")}
        return target in names


def clean_body(body: str) -> str:
    """Cosmetic only: drop leading comment-continuation stars, collapse spaces."""
    lines = [re.sub(r"^\s*\*\s?", "", line) for line in body.splitlines()]
    return " ".join(" ".join(lines).split())


