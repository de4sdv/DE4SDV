def _inventory():  # type: ignore[no-untyped-def]
    from de4sdv.semantic import authority_inventory

    return authority_inventory


class _Model:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.files: dict[str, _Source] = {}
        self.used: set[str] = set()

    def source(self, relative: str) -> _Source:
        if relative not in self.files:
            path = self.root / relative
            if ".." in Path(relative).parts or not path.is_file():
                raise DefinitionBatch2Error(f"governed model file missing: {relative}")
            self.files[relative] = _Source(relative, path.read_text(encoding="utf-8"))
        return self.files[relative]


def _successor_records(model: _Model) -> dict[str, Any]:
    source = model.source(SUCCESSOR_FILE)
    package = source.owner_block(f"package {SUCCESSOR_PACKAGE}")
    relations = {
        name: source.record_fields(span, SUCCESSOR_RECORD_FIELDS, name)
        for name, span in source.direct_record_usages(package, "SuccessorRelationRecord").items()
    }
    retirements = {
        name: source.record_fields(span, RETIREMENT_RECORD_FIELDS, name)
        for name, span in source.direct_record_usages(package, "SuccessorRetirementRecord").items()
    }
    versions = [
        source.record_fields(span, VERSION_RECORD_FIELDS, name)
        for name, span in source.direct_record_usages(package, "SuccessorVersionRecord").items()
    ]
    _require(len(versions) == 1, f"{SUCCESSOR_FILE}: exactly one SuccessorVersionRecord usage is required")
    _require(versions[0]["version"] == SUCCESSOR_CONTRACT,
             f"{SUCCESSOR_FILE}: successor version must be {SUCCESSOR_CONTRACT}")
    return {"relations": relations, "retirements": retirements, "version": versions[0]}


def _definition_text(model: _Model, row: dict[str, Any]) -> tuple[dict[str, Any], str]:
    identity = row["identity"]
    home = row["home"]
    source = model.source(home["file"])
    block = source.owner_block(home["owner"])
    annotations = source.direct_annotations(block)
    form = home["form"]
    if form in ("owned-doc", "named-doc"):
        name = home.get("name")
        docs = [a for a in annotations if a["kind"] == "doc" and a["name"] == (name if form == "named-doc" else None)]
        _require(len(docs) > home["index"],
                 f"{identity}: {home['owner']} owns no {'named ' + name if name else 'anonymous'} documentation at index {home['index']}")
        body = clean_body(docs[home["index"]]["body"])
        normalize = _inventory().normalize_text
        observation = "normalized-exact" if normalize(body) == normalize(row["reviewed_definition"]) else "differs"
        _require(observation == "normalized-exact",
                 f"{identity}: model documentation and reviewed definition differ (batch 2 admits normalized-exact only)")
        witness = {"source_file": home["file"], "owner": home["owner"], "form": form,
                   "documentation_name": name, "documentation_index": home["index"]}
        return {"documentation": body, "documentation_witness": witness,
                "documentation_observation": observation}, form
    if form == "vocabulary-role":
        comments = [a for a in annotations if a["kind"] == "comment" and a["name"] == home["name"]]
        _require(len(comments) == 1, f"{identity}: {home['owner']} must own exactly one comment {home['name']}")
        comment = comments[0]
        _require(comment["about"] == home["about"],
                 f"{identity}: {home['name']} annotates {comment['about']} not {home['about']}")
        for target in comment["about"]:
            other = home["about_imports"].get(target)
            if other is None:
                _require(source.defines(target) or source.names_documentation(target),
                         f"{identity}: about target {target} is not a definition or named documentation of {home['file']}")
                continue
            # Cross-file target: defined in the named file's single top-level
            # package, which the home file imports directly (wildcard or exact).
            defining = model.source(other)
            model.used.add(other)
            _require(defining.defines(target), f"{identity}: about target {target} is not defined in {other}")
            packages = [m[1] for m in re.finditer(r"\bpackage\s+([A-Za-z_]\w*)(?=\s*\{)", defining.mask)
                        if defining.depth[m.start()] == 0]
            _require(len(packages) == 1, f"{identity}: {other} must own exactly one top-level package")
            _require(re.search(r"\bimport\s+" + re.escape(packages[0]) + r"::(?:" + re.escape(target) + r"|\*)\s*;",
                               source.mask) is not None,
                     f"{identity}: {home['file']} does not import {packages[0]} for about target {target}")
        body = clean_body(comment["body"])
        _require(bool(body), f"{identity}: {home['name']} has an empty body")
        witness = {"source_file": home["file"], "owner": home["owner"], "form": form,
                   "comment_name": home["name"], "about": list(home["about"]),
                   "about_imports": dict(sorted(home["about_imports"].items()))}
        return {"documentation": body, "documentation_witness": witness,
                "documentation_observation": "model-owned-vocabulary-role"}, form
    raise DefinitionBatch2Error(f"{identity}: unsupported text home {form}")


def _representation(row: dict[str, Any]) -> tuple[str, str]:
    home = row["home"]
    if row["home"]["form"] in ("vocabulary-role", "retirement-record"):
        return FORM_REPRESENTATION[home["form"]]
    owner = home["owner"]
    definition = _DEF_OWNER.match(owner)
    if definition:
        keyword = definition["kind"]
        _require(keyword in REPRESENTATION_CLASSES, f"{row['identity']}: unsupported declaration kind {keyword!r}")
        return REPRESENTATION_CLASSES[keyword], API_METACLASSES[keyword]
    return FORM_REPRESENTATION["package-doc"]


def _end_pair(model: _Model, record_name: str, record: dict[str, str]) -> dict[str, Any]:
    source = model.source(SUCCESSOR_FILE)
    carrier = f"connection def {record['carrier']}"
    ends = source.carrier_ends(carrier)
    return {
        "record": record_name,
        "carrier": {"source_file": SUCCESSOR_FILE, "declaration": carrier, "ends": ends},
        "mechanism": record["mechanism"],
        "semantic_strength": record["strength"],
        "source_class": record["sourceClass"],
        "target_class": record["targetClass"],
        "source_usage": record["sourceUsage"],
        "target_usage": record["targetUsage"],
        "inverse_navigation": record["inverse"] or None,
    }


def _external_profile(root: Path) -> dict[str, dict[str, Any]]:
    import yaml

    path = root / EXTERNAL_REFERENCE_PROFILE_PATH
    _require(path.is_file(), f"external-reference profile missing: {EXTERNAL_REFERENCE_PROFILE_PATH}")
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    entries = document.get("profile_entries") if isinstance(document, dict) else None
    _require(isinstance(entries, list), "external-reference profile has no profile_entries")
    return {str(entry.get("identity")): entry for entry in entries if isinstance(entry, dict)}


def _row_outputs(root: Path, model: _Model, row: dict[str, Any], successors: dict[str, Any],
                 external: dict[str, dict[str, Any]], inputs: set[str]) -> tuple[dict[str, Any], dict[str, Any]]:
    identity = row["identity"]
    admission = row["admission_class"]
    home = row["home"]
    inputs.add(home["file"])
    representation_class, metaclass = _representation(row)
    projection: dict[str, Any] = {
        "identity": identity,
        "semantic_kind": row["semantic_kind"],
        "admission_class": admission,
        "register_wave": row["register"]["wave"],
        "accounting": row["register"]["accounting"],
        "boundary": row["boundary"],
    }
    profile: dict[str, Any] = {
        "profile_identity": f"{PROFILE_SCHEMA}#{identity}",
        "for_concept": identity,
        "representation_class": representation_class,
        "binding_contract_echo": {"source_file": home["file"], "owner": home["owner"], "api_metaclass": metaclass},
        "witness_forms": [WITNESS_FORMS[home["form"]]],
    }
    if home["form"] == "retirement-record":
        retirement = successors["retirements"].get(home["name"])
        _require(retirement is not None, f"{identity}: retirement record {home['name']} not found")
        _require(retirement["predicate"] == identity,
                 f"{identity}: retirement record {home['name']} retires {retirement['predicate']}")
        projection["definition"] = {
            "documentation": retirement["reason"],
            "documentation_witness": {"source_file": home["file"], "owner": home["owner"],
                                      "form": "retirement-record", "record": home["name"]},
            "documentation_observation": "model-owned-retirement-record",
        }
    else:
        projection["definition"], _ = _definition_text(model, row)
    if row["semantic_kind"] == "class":
        grounding = row["grounding"]
        mapping = grounding["kernel_mapping"]
        if "file" in mapping:
            source = model.source(mapping["file"])
            source.owner_block(mapping["declaration"])
            inputs.add(mapping["file"])
            ground: dict[str, Any] = {"kernel_binding_contract": {"source_file": mapping["file"],
                                                                  "declaration": mapping["declaration"]}}
        elif "native" in mapping:
            ground = {"kernel_native": mapping["native"]}
        else:
            ground = {"kernel_external": mapping["external"]}
        ground["ontology_relations"] = {"sub_class_of": grounding["sub_class_of"],
                                        "disjoint_with": list(grounding["disjoint_with"])}
        ground["contract_source"] = (
            "kernel mapping kind and ontology relations: reviewed manifest fields "
            "(test-locked to the authored ontology); file mappings are resolved "
            "in the model by this generator"
        )
        projection["grounding"] = ground
    if admission == "successor":
        names = row["successor"]["records"]
        matching = sorted(name for name, record in successors["relations"].items() if record["predicate"] == identity)
        _require(matching == sorted(names),
                 f"{identity}: model successor records {matching} != manifest {sorted(names)}")
        pairs = [_end_pair(model, name, successors["relations"][name]) for name in names]
        inverses = sorted({pair["inverse_navigation"] for pair in pairs if pair["inverse_navigation"]})
        projection["successor"] = {
            "contract": SUCCESSOR_CONTRACT,
            "version_supersedes": successors["version"]["supersedes"],
            "end_pairs": pairs,
            "inverse_navigation": inverses,
            "contract_source": "model successor relation records and carrier ends (generator-extracted)",
        }
        profile["successor_mechanics"] = [
            {"record": pair["record"], "mechanism": pair["mechanism"],
             "carrier": pair["carrier"]["declaration"], "source_usage": pair["source_usage"],
             "target_usage": pair["target_usage"]}
            for pair in pairs
        ]
    elif row["semantic_kind"] == "relationship":
        relation = row["relation"]
        projection["relation"] = {
            "domain": {"ontology_class": relation["domain"]},
            "range": {"ontology_class": relation["range"]},
            "canonical_direction": f"{relation['domain']} -> {relation['range']}",
            "semantic_strength": relation["semantic_strength"],
            "contract_source": (
                "domain/range/strength: reviewed manifest fields (test-locked to "
                "the authored ontology); not a structural model witness"
            ),
        }
    if "carrier" in row:
        carrier = row["carrier"]
        source = model.source(carrier["file"])
        inputs.add(carrier["file"])
        projection["carrier"] = {"source_file": carrier["file"], "declaration": carrier["declaration"],
                                 "ends": source.carrier_ends(carrier["declaration"])}
    if "range_discriminator" in row:
        disc = row["range_discriminator"]
        lineage = disc["lineage"]
        model.source(lineage["file"]).owner_block(lineage["declaration"])
        inputs.add(lineage["file"])
        target = _DEF_OWNER.match(lineage["declaration"])["name"]  # type: ignore[index]
        for pin in disc["closure"]:
            source = model.source(pin["file"])
            inputs.add(pin["file"])
            _require(source.specializes(pin["declaration"], target),
                     f"{identity}: closure pin {pin['declaration']} does not specialize {target}")
            _require(re.search(r"\bimport\s+DE4SDV_MethodContext::(?:" + re.escape(target) + r"|\*)\s*;",
                               source.mask) is not None,
                     f"{identity}: {pin['file']} does not import the owning kernel package")
        projection["relation"]["range"]["discriminator"] = {
            "kind": "type-lineage",
            "lineage": {"source_file": lineage["file"], "declaration": lineage["declaration"]},
            "closure": [{"source_file": p["file"], "declaration": p["declaration"]} for p in disc["closure"]],
            "rule": (
                "a target is in range iff its definition is in the specialization "
                "closure of the kernel lineage declaration, resolved through the "
                "governed kernel mapping; never by name, prefix or membership heuristic"
            ),
        }
    if "mechanics" in row:
        profile["serializer_mechanics"] = dict(row["mechanics"])
        profile["mechanics_source"] = (
            "reviewed manifest field equal to the authored mapping (test-locked); "
            "Wave C retires the authored copy"
        )
    if admission == "deprecated-alias":
        alias = row["alias"]
        relations = successors["relations"]
        pairs = [r for r in relations.values() if r["predicate"] == alias["successor"]
                 and r["carrier"] == alias["successor_carrier"]]
        _require(len(pairs) == 1,
                 f"{identity}: successor {alias['successor']} has no unique record over {alias['successor_carrier']}")
        navigation = alias["successor"]
        if alias["direction"] == "inverse":
            _require(bool(pairs[0]["inverse"]), f"{identity}: inverse alias needs a successor inverse navigation")
            navigation = pairs[0]["inverse"]
        projection["alias"] = {
            "deprecated": True,
            "successor": alias["successor"],
            "successor_navigation": navigation,
            "successor_carrier": alias["successor_carrier"],
            "direction": alias["direction"],
            "answer_mode": alias["answer_mode"],
            "removal": "Wave C (with the authored ontology)",
            "rule": (
                "documented deprecated name: answers are the successor's facts over "
                "this carrier with the successor's meaning; the old signature and "
                "claim are never translated into the successor"
                if alias["answer_mode"] == "successor-facts" else
                "documented deprecated name only: no fact is answered under this "
                "name (the model retirement record refuses an alias reading); "
                "query the successor"
            ),
        }
        profile["alias_resolution"] = {"successor": alias["successor"], "navigation": navigation,
                                       "carrier": alias["successor_carrier"],
                                       "answer_mode": alias["answer_mode"]}
    if "external_reference" in row:
        entry = external.get(identity)
        _require(entry is not None, f"{identity}: not an entry of the accepted external-reference profile")
        _require(entry.get("accepted_ref") == row["external_reference"]["accepted_ref"],
                 f"{identity}: accepted_ref differs from the accepted external-reference profile")
        inputs.add(EXTERNAL_REFERENCE_PROFILE_PATH)
        profile["external_reference"] = {
            "profile": EXTERNAL_REFERENCE_PROFILE_PATH,
            "accepted_ref": entry["accepted_ref"],
            "representation_class": entry.get("representation_class"),
        }
    if row["boundary"] == "ple-no-configurator-authority":
        profile["configurator_authority"] = "none (external catalogue, ADR 0006; decision-9)"
    projection["support"] = SUPPORT[admission]
    projection["traversal"] = False
    projection["api_identity"] = "unclaimed"
    return projection, profile


def build_outputs(root: Path, document: dict[str, Any]) -> dict[str, Any]:
    model = _Model(root)
    successors = _successor_records(model)
    external = _external_profile(root) if any("external_reference" in r for r in document["admitted"]) else {}
    inputs: set[str] = {SUCCESSOR_FILE}
    # (cross-file about targets are added to model.used while rows are built)
    projection_rows = []
    profile_entries = []
    for row in document["admitted"]:
        projection, profile = _row_outputs(root, model, row, successors, external, inputs)
        projection_rows.append(projection)
        profile_entries.append(profile)
    inputs |= model.used
    projection_rows.sort(key=lambda item: item["identity"])
    profile_entries.sort(key=lambda item: item["for_concept"])
    exceptions = sorted(
        ({"identity": e["identity"], "accounting": e["accounting"], "reason": e["reason"]}
         for e in document["exceptions"]), key=lambda e: e["identity"])
    return {
        "admitted": sorted(row["identity"] for row in document["admitted"]),
        "projection_rows": projection_rows,
        "profile_entries": profile_entries,
        "exceptions": exceptions,
        "model_inputs": sorted(inputs),
    }


def collect_bound_inputs(root: Path, outputs: dict[str, Any]) -> dict[str, str]:
    from de4sdv.semantic.authority_inventory import file_digest

    paths = {ADMISSION_PATH, DESIGN_PATH, MODULE_PATH, GENERATOR_PATH,
             AUTHORITY_INVENTORY_PATH, PROJECTION_O2P_PATH, *outputs["model_inputs"]}
    bound: dict[str, str] = {}
    for relative in sorted(paths):
        _require((root / relative).is_file(), f"bound input missing: {relative}")
        bound[relative] = file_digest(root, relative)
    return bound


