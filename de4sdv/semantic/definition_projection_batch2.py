def _require(condition: bool, message: str) -> None:
    if not condition:
        raise DefinitionBatch2Error(message)


def _nonempty(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip()) and value == value.strip()


def _validate_home(identity: str, home: Any) -> None:
    _require(isinstance(home, dict), f"{identity}: home must be a mapping")
    form = home.get("form")
    _require(form in HOME_FORMS, f"{identity}: home.form must be one of {sorted(HOME_FORMS)}")
    _require(set(home) == _HOME_KEYS[form],
             f"{identity}: home keys {sorted(home)} != {sorted(_HOME_KEYS[form])}")
    _require(_nonempty(home["file"]) and ".." not in Path(home["file"]).parts
             and home["file"].startswith("textual-notation-of-model/"),
             f"{identity}: home.file must be a governed model path")
    owner = home["owner"]
    _require(isinstance(owner, str) and (_DEF_OWNER.match(owner) or _PACKAGE_OWNER.match(owner)),
             f"{identity}: home.owner must be 'package X' or '<kind> def X'")
    if form in ("named-doc", "vocabulary-role", "retirement-record"):
        _require(isinstance(home["name"], str) and _IDENT.match(home["name"]) is not None,
                 f"{identity}: home.name must be an identifier")
    if form in ("owned-doc", "named-doc"):
        _require(isinstance(home["index"], int) and not isinstance(home["index"], bool)
                 and home["index"] >= 0, f"{identity}: home.index must be a non-negative integer")
    if form == "vocabulary-role":
        _require(_PACKAGE_OWNER.match(owner) is not None,
                 f"{identity}: a vocabulary-role comment must be package-owned")
        _require(home["name"].endswith("VocabularyRole"),
                 f"{identity}: vocabulary-role names end in VocabularyRole")
        about = home["about"]
        _require(isinstance(about, list) and about and all(isinstance(a, str) and _IDENT.match(a) for a in about)
                 and len(set(about)) == len(about), f"{identity}: home.about must list unique identifiers")
        imports = home["about_imports"]
        _require(isinstance(imports, dict) and set(imports) <= set(about) and all(
            _nonempty(path) and path.startswith("textual-notation-of-model/") and ".." not in Path(path).parts
            for path in imports.values()),
            f"{identity}: home.about_imports maps about targets to their defining governed model file")
    if form == "retirement-record":
        _require(home["file"] == SUCCESSOR_FILE and owner == f"package {SUCCESSOR_PACKAGE}",
                 f"{identity}: retirement records live in the relationship-successor package")


def _validate_gates(identity: str, row: dict[str, Any]) -> None:
    gates = row["gates"]
    _require(isinstance(gates, list), f"{identity}: gates must be a list")
    seen = set()
    for gate in gates:
        _require(isinstance(gate, dict) and set(gate) == {"gate", "resolved_by"},
                 f"{identity}: each gate carries exactly gate and resolved_by")
        _require(isinstance(gate["gate"], str) and re.fullmatch(r"decision-\d+|row-blocker", gate["gate"]) is not None,
                 f"{identity}: gate must be decision-N or row-blocker")
        _require(gate["gate"] not in seen, f"{identity}: duplicate gate {gate['gate']}")
        seen.add(gate["gate"])
        refs = gate["resolved_by"]
        _require(isinstance(refs, list) and refs and all(
            isinstance(ref, str) and re.fullmatch(r"docs/[A-Za-z0-9_./-]+\.(?:md|yaml)#[A-Za-z0-9_.-]+", ref)
            and ".." not in ref for ref in refs), f"{identity}: resolved_by must list docs/ record fragments")
    obligations = row["forward_obligations"]
    _require(isinstance(obligations, list) and all(_nonempty(item) for item in obligations),
             f"{identity}: forward_obligations must list non-empty strings")


def _validate_row(row: Any) -> str:
    _require(isinstance(row, dict), "admitted rows must be mappings")
    identity = row.get("identity")
    _require(isinstance(identity, str) and _IDENT.match(identity) is not None, "admitted row missing identity")
    kind = row.get("semantic_kind")
    _require(kind in SEMANTIC_KINDS, f"{identity}: semantic_kind must be class or relationship")
    admission = row.get("admission_class")
    _require(admission in ADMISSION_CLASSES, f"{identity}: unknown admission_class {admission!r}")
    expected_kind = ADMISSION_CLASSES[admission]
    _require(expected_kind in (None, kind), f"{identity}: admission_class {admission} requires {expected_kind}")
    allowed = _COMMON_KEYS | (_CLASS_KEYS if kind == "class" else _RELATIONSHIP_KEYS)
    extra = set(row) - allowed
    _require(not extra, f"{identity}: unknown keys {sorted(extra)}")
    missing = _COMMON_KEYS - set(row)
    _require(not missing, f"{identity}: missing keys {sorted(missing)}")
    register = row["register"]
    _require(isinstance(register, dict) and set(register) == {"wave", "accounting"}
             and register["accounting"] in ACCOUNTING
             and (register["wave"] is None or re.fullmatch(r"W[2-6]|closure", str(register["wave"]))),
             f"{identity}: register must carry wave and accounting")
    _require((register["wave"] is None) == (register["accounting"] != "retained"),
             f"{identity}: only retained rows carry a register wave")
    _require(row["boundary"] in BOUNDARIES, f"{identity}: unknown boundary")
    _validate_home(identity, row["home"])
    form = row["home"]["form"]
    reviewed = row["reviewed_definition"]
    if form in ("owned-doc", "named-doc"):
        _require(_nonempty(reviewed), f"{identity}: a documentation home needs the reviewed definition oracle")
    else:
        _require(reviewed is None, f"{identity}: {form} homes carry no authored definition")
    _validate_gates(identity, row)
    if kind == "class":
        _require(form in ("owned-doc", "named-doc"), f"{identity}: classes need a definition documentation home")
        grounding = row.get("grounding")
        _require(isinstance(grounding, dict) and set(grounding) == {"kernel_mapping", "sub_class_of", "disjoint_with"},
                 f"{identity}: grounding carries kernel_mapping, sub_class_of and disjoint_with")
        mapping = grounding["kernel_mapping"]
        _require(isinstance(mapping, dict) and (
            (set(mapping) == {"file", "declaration"} and all(_nonempty(mapping[k]) for k in mapping)
             and _DEF_OWNER.match(mapping["declaration"]) is not None)
            or (set(mapping) == {"native"} and _nonempty(mapping["native"]))
            or (set(mapping) == {"external"} and _nonempty(mapping["external"]))),
            f"{identity}: kernel_mapping must be exactly file+declaration, native or external")
        _require(grounding["sub_class_of"] is None or _IDENT.match(str(grounding["sub_class_of"])) is not None,
                 f"{identity}: sub_class_of must be an identity or null")
        disjoint = grounding["disjoint_with"]
        _require(isinstance(disjoint, list) and all(_IDENT.match(str(x)) for x in disjoint),
                 f"{identity}: disjoint_with must list identities")
    else:
        if admission != "successor":
            relation = row.get("relation")
            _require(isinstance(relation, dict) and set(relation) == {"domain", "range", "semantic_strength"}
                     and _IDENT.match(str(relation["domain"])) and _IDENT.match(str(relation["range"]))
                     and (relation["semantic_strength"] is None or _nonempty(relation["semantic_strength"])),
                     f"{identity}: relation carries domain, range and semantic_strength")
        else:
            _require("relation" not in row, f"{identity}: successor end pairs come from the model records")
    has = {key: key in row for key in ("mechanics", "range_discriminator", "successor", "alias", "external_reference", "carrier")}
    _require(has["successor"] == (admission == "successor"), f"{identity}: successor block iff admission_class successor")
    _require(has["alias"] == (admission == "deprecated-alias"), f"{identity}: alias block iff deprecated-alias")
    _require(form == "retirement-record" if admission == "deprecated-alias" else form != "retirement-record",
             f"{identity}: deprecated aliases (and only they) are homed by a retirement record")
    if admission == "relationship-runtime":
        _require(has["mechanics"], f"{identity}: runtime-mapped rows carry serializer mechanics")
    if has["mechanics"]:
        mechanics = row["mechanics"]
        _require(admission in ("relationship-runtime", "external-reference") and isinstance(mechanics, dict)
                 and _nonempty(mechanics.get("strategy")) and "semantic_strength" not in mechanics,
                 f"{identity}: mechanics need a strategy and no semantic_strength")
    if has["range_discriminator"]:
        disc = row["range_discriminator"]
        _require(isinstance(disc, dict) and set(disc) == {"kind", "lineage", "closure"} and disc["kind"] == "type-lineage",
                 f"{identity}: range_discriminator carries kind type-lineage, lineage and closure")
        for pin in [disc["lineage"], *disc["closure"]]:
            _require(isinstance(pin, dict) and set(pin) == {"file", "declaration"}
                     and _nonempty(pin["file"]) and _DEF_OWNER.match(str(pin["declaration"])) is not None,
                     f"{identity}: discriminator pins carry file and declaration")
        _require(len({(p["file"], p["declaration"]) for p in disc["closure"]}) == len(disc["closure"]) > 0,
                 f"{identity}: discriminator closure pins must be non-empty and unique")
    if has["external_reference"]:
        ref = row["external_reference"]
        _require(admission == "external-reference" and isinstance(ref, dict) and set(ref) == {"accepted_ref"}
                 and _nonempty(ref["accepted_ref"]), f"{identity}: external_reference carries accepted_ref")
    if admission == "external-reference":
        _require(row["boundary"] == "external-content", f"{identity}: external references keep the external-content boundary")
    if has["carrier"]:
        carrier = row["carrier"]
        _require(isinstance(carrier, dict) and set(carrier) == {"file", "declaration"}
                 and _nonempty(carrier["file"]) and str(carrier["declaration"]).startswith("connection def "),
                 f"{identity}: carrier carries file and a connection def declaration")
    if has["successor"]:
        successor = row["successor"]
        _require(isinstance(successor, dict) and set(successor) == {"records"}
                 and isinstance(successor["records"], list) and successor["records"]
                 and all(isinstance(r, str) and _IDENT.match(r) for r in successor["records"])
                 and len(set(successor["records"])) == len(successor["records"]),
                 f"{identity}: successor.records must list unique record usage names")
    if has["alias"]:
        alias = row["alias"]
        _require(isinstance(alias, dict) and set(alias) == {"successor", "successor_carrier", "direction", "answer_mode"}
                 and _IDENT.match(str(alias["successor"])) and _IDENT.match(str(alias["successor_carrier"]))
                 and alias["direction"] in ("forward", "inverse")
                 and alias["answer_mode"] in ("successor-facts", "documentation-only"),
                 f"{identity}: alias carries successor, successor_carrier, direction and answer_mode")
    if row["boundary"] == "ple-no-configurator-authority":
        _require(admission in ("definition", "relationship-vocabulary"),
                 f"{identity}: PLE configuration rows stay vocabulary-only")
    return identity


def load_admission(path: Path) -> dict[str, Any]:
    """Load and shape-lock the governed batch-2 admission document."""
    import yaml

    if not path.is_file():
        raise DefinitionBatch2Error(f"batch-2 admission document missing: {path}")
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    _require(isinstance(document, dict), f"batch-2 admission document malformed: {path}")
    _require(document.get("schema") == ADMISSION_SCHEMA,
             f"batch-2 admission schema must be {ADMISSION_SCHEMA}: {document.get('schema')!r}")
    _require(_nonempty(document.get("status")), "batch-2 admission status is required")
    admitted = document.get("admitted")
    _require(isinstance(admitted, list) and bool(admitted), "batch-2 admitted rows are required (non-empty list)")
    seen: set[str] = set()
    for row in admitted:
        identity = _validate_row(row)
        _require(identity not in seen, f"{identity}: duplicate admitted identity")
        seen.add(identity)
    exceptions = document.get("exceptions")
    _require(isinstance(exceptions, list), "batch-2 exceptions must be a list (owner-visible, may be empty)")
    for entry in exceptions:
        _require(isinstance(entry, dict) and set(entry) == {"identity", "accounting", "reason"}
                 and _IDENT.match(str(entry["identity"])) and _nonempty(entry["reason"])
                 and entry["accounting"] in ("retained", "unregistered", "merged", "removed"),
                 "each exception carries identity, accounting and a non-empty reason")
        _require(entry["identity"] not in seen, f"{entry['identity']}: an exception cannot also be admitted")
    return document


def load_document(root: Path) -> dict[str, Any]:
    return load_admission(root / ADMISSION_PATH)


