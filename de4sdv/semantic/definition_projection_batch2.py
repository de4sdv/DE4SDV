"""O4 definition-admission batch 2: governed projection + API profile for the
remaining retained identities.

Batch 2 makes every retained O4 register row that no other generated layer
projects (O2 chain / O3 13, definition batch 1, O2+, W4 vocabulary carriers)
model-projected, together with the ontology-mapped classes that are not O4
register rows (successor and scoped-assurance classes) and the owner-exposed
W6 successor predicates. It is a SEPARATE pair from batch 1
(``definition-projection.json`` / ``definition-profile.json`` stay byte-stable
in content), generated by the same generator script.

Every admitted row is backed by a model-resident home that the generator
locates and reads itself, fail-closed:

* ``owned-doc`` / ``named-doc`` — a definition declaration (``<kind> def``) or
  a package, and ONE directly owned Documentation (anonymous or named, selected
  by name + index). The reviewed definition is the parity oracle; the recomputed
  observation must be ``normalized-exact`` (cosmetic normalization only).
* ``vocabulary-role`` — a directly owned named comment
  ``comment <Name> about <targets> /* ... */`` of the owning package; every
  ``about`` target must be a live definition or named documentation of the
  same file. These rows have no authored definition text; the comment body is
  the model-owned vocabulary role and claim boundary.
* ``retirement-record`` — a directly owned ``SuccessorRetirementRecord`` usage
  of the relationship-successor package whose ``predicate`` equals the
  identity (deprecated aliases).

Successor rows additionally carry every directly owned
``SuccessorRelationRecord`` usage whose ``predicate`` equals the identity (set
equality with the manifest, fail-closed) plus the typed ends of each carrier
``connection def``. The ``hasRelevantEvidenceContract`` row carries the
owner-adopted type-lineage range discriminator: the kernel
``requirement def EvidenceContract`` and the exact specialization closure pins,
each verified to specialize ``EvidenceContract`` with a direct import of the
owning kernel package.

Contract fields the model does not structurally carry (relationship
domain/range of vocabulary-only predicates, kernel mapping kind of
native/external classes, serializer mechanics of the runtime-mapped
predicates) are reviewed manifest fields; tests lock them byte-for-byte to the
authored ontology until Wave C deletes it. They are labeled as such in every
generated row (``contract_source``); nothing is inferred from names.

Boundaries: generation reads ONLY the admission manifest, the governed model
files named by it and the accepted external-reference profile (for the
external-reference echo). No O1 artifact, no register and no authored
ontology is read here. No runtime module imports this machinery. Rows claim no
traversal proof and no API element identity; deprecated aliases never
translate an old signature into a broader successor contract.

Read-only and offline; never imported by the runtime.
"""
