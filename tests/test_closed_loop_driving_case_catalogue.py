@pytest.mark.parametrize("which, old, new, message", [row[1:] for row in FAIL_CLOSED],
                         ids=[row[0] for row in FAIL_CLOSED])
def test_the_generator_fails_closed(which, old, new, message) -> None:
    """Each rule refuses with its own message on the synthetic text changed in one place.

    Cannot see: a wrong model that keeps every form the generator reads (a case that verifies the wrong
    requirement through a well-formed verify); the model's own tests and Syside judge that.
    """
    gen = _generator()
    evidence, requirements = SYNTHETIC_EVIDENCE, SYNTHETIC_REQUIREMENTS
    if which == "evidence":
        evidence = _with(evidence, old, new)
    else:
        requirements = _with(requirements, old, new)
    with pytest.raises(gen.CatalogueError, match=re.escape(message)):
        gen.catalogue_from_text(evidence, requirements)


