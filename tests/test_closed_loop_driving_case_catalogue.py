def test_the_catalogue_holds_six_outcomes_four_scenarios_and_35_cases() -> None:
    """The tracked file: its schema and sources, six outcomes, four scenarios, the cases VC-DRIVING-001 to -035 in
    id order with the usage and definition an independent regular expression reads from the model, and each case
    verifying the requirement of its own number (owner decision 1 of 2026-11-06, one case per requirement, which
    ``test_closed_loop_driving_verification_evidence.py`` pins in the model).

    Cannot see: a requirement id that is right in number but declared for another requirement text.
    """
    data = _catalogue()
    assert list(data) == ["schema", "generated_from", "outcomes", "verdicts", "verdict_otherwise", "scenarios",
                          "cases"]
    assert data["schema"] == "de4sdv.driving.case-catalogue.v1"
    assert data["generated_from"] == [EVIDENCE, REQUIREMENTS]
    assert len(data["outcomes"]) == len(set(data["outcomes"])) == 6
    assert len(data["scenarios"]) == len(set(data["scenarios"])) == 4
    assert [case["id"] for case in data["cases"]] == [f"VC-DRIVING-{n:03d}" for n in range(1, CASE_COUNT + 1)]
    evidence, _ = _real_model()
    usages = sorted(re.findall(r"verification <'(VC-DRIVING-\d{3})'> (\w+) : (\w+) \{", evidence))
    assert [(case["id"], case["usage"], case["definition"]) for case in data["cases"]] == usages
    for case in data["cases"]:
        assert list(case) == ["id", "usage", "definition", "requirement"], case
        assert case["requirement"] == case["id"].replace("VC-DRIVING-", "REQ-DRIVING-"), case


