"""The case catalogue of the closed-loop driving bench, generated from the SysML model.

``scripts/generate_driving_case_catalogue.py`` reads two files of the driving model as text and writes
``implementation/closed-loop-driving-bench/case-evaluators/driving_case_catalogue.json``: the
DrivingEvidenceOutcome literals, the verdict of each by MapDrivingEvidenceOutcomeToVerdict, the
DrivingScenarioIdentity literals and the verification cases with the requirement each one verifies. The
bench's evaluators read the file at import and keep no hand copy of it.

These tests check the generator on the real model, each of its fail-closed rules on small synthetic model text
built here or on the real text changed in memory, the evaluators read with ``ast`` (never imported: this
interpreter has no numpy), and the three conventions of a gate of ``scripts/check_repo.py``. The reading is
lexical; the licensed Syside run validates the model.
"""

from __future__ import annotations

import ast
import contextlib
import importlib
import json
import re
import sys
from pathlib import Path
from unittest import mock

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

EVIDENCE = "textual-notation-of-model/packages/features/driving/closed_loop_driving_verification_evidence.sysml"
REQUIREMENTS = "textual-notation-of-model/packages/features/driving/closed_loop_driving_needs_requirements.sysml"
EVALUATORS = ROOT / "implementation" / "closed-loop-driving-bench" / "case-evaluators"
CATALOGUE = EVALUATORS / "driving_case_catalogue.json"
REGENERATE = ("python3 scripts/generate_driving_case_catalogue.py --output "
              "implementation/closed-loop-driving-bench/case-evaluators/driving_case_catalogue.json")
CASE_COUNT = 35
#: The outcome constants of cases.py, by the names the evaluators use.
OUTCOME_CONSTANTS = ("PASS", "FAIL", "INCONCL", "ERROR", "BLOCKED")
#: The literals of the standard library's VerdictKind.
VERDICT_WORDS = ("pass", "fail", "inconclusive", "error")
EVALUATOR_MODULES = ("cases.py", "evaluate_run.py", "evaluate_campaign.py")


def _generator():
    """The generator module, imported per test, so that each test fails on its own while the module is missing."""
    return importlib.import_module("scripts.generate_driving_case_catalogue")


def _catalogue() -> dict:
    return json.loads(CATALOGUE.read_text(encoding="utf-8"))


def _real_model() -> tuple[str, str]:
    return ((ROOT / EVIDENCE).read_text(encoding="utf-8"), (ROOT / REQUIREMENTS).read_text(encoding="utf-8"))


def _with(text: str, old: str, new: str) -> str:
    """``text`` with ``old`` replaced; ``old`` must occur exactly once, so that a change that no longer applies fails."""
    assert text.count(old) == 1, f"the change does not apply exactly once: {old!r}"
    return text.replace(old, new)


