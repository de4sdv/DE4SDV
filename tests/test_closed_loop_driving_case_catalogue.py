def test_the_check_names_the_regeneration_command_when_the_file_is_missing_or_differs(tmp_path, capsys) -> None:
    """``run_check_errors(root)`` on a copy of the two model files: a missing catalogue, a verdict changed by
    hand and the same text with other line endings are each one error that names the regeneration command, and
    ``--check`` exits 1 with that message.

    Cannot see: the check on another tree than the copy it is given.
    """
    gen = _generator()
    for relative in (EVIDENCE, REQUIREMENTS):
        (tmp_path / relative).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / relative).write_bytes((ROOT / relative).read_bytes())
    missing = gen.run_check_errors(tmp_path)
    assert len(missing) == 1 and "not found" in missing[0] and REGENERATE in missing[0], missing
    tracked = tmp_path / CATALOGUE.relative_to(ROOT)
    tracked.parent.mkdir(parents=True)
    tracked.write_bytes(CATALOGUE.read_bytes())
    assert gen.run_check_errors(tmp_path) == []
    tracked.write_bytes(CATALOGUE.read_bytes().replace(b"\n", b"\r\n"))
    crlf = gen.run_check_errors(tmp_path)
    assert len(crlf) == 1 and "drifted" in crlf[0] and REGENERATE in crlf[0], crlf
    data = _catalogue()
    data["verdicts"]["failObservedBehavior"] = "pass"
    tracked.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    drift = gen.run_check_errors(tmp_path)
    assert len(drift) == 1 and "drifted" in drift[0] and REGENERATE in drift[0], drift
    capsys.readouterr()
    with mock.patch.object(gen, "ROOT", tmp_path):
        assert gen.main(["--check"]) == 1
    assert REGENERATE in capsys.readouterr().out


def test_the_output_is_deterministic_and_names_no_time_commit_or_host_path(tmp_path, capsys) -> None:
    """Two generations give the same bytes, serialized as the AEBS scenario manifest is (indent 2, UTF-8, one
    final newline); stdout and ``--output`` write those bytes; nothing in them is a time, a commit id or a path
    of this host.

    Cannot see: a time or host value the generator might take from the environment in another format.
    """
    gen = _generator()
    first = gen.serialize(gen.generate_catalogue())
    assert first == gen.serialize(gen.generate_catalogue())
    assert first == json.dumps(json.loads(first), indent=2, ensure_ascii=False) + "\n"
    assert str(ROOT) not in first and "/home/" not in first
    assert not re.search(r"\b[0-9a-f]{40}\b", first) and not re.search(r"\d{4}-\d{2}-\d{2}T\d", first)
    out = tmp_path / "catalogue.json"
    assert gen.main(["--output", str(out)]) == 0
    assert out.read_bytes() == first.encode("utf-8")
    capsys.readouterr()
    assert gen.main([]) == 0
    assert capsys.readouterr().out == first


