# -- the evaluators, read with ast ---------------------------------------------------------------------------


def _module(name: str) -> ast.Module:
    return ast.parse((EVALUATORS / name).read_text(encoding="utf-8"), filename=name)


def _assignments(tree: ast.Module) -> dict[str, ast.expr]:
    """The module-level ``NAME = value`` assignments; the last one wins, as at run time."""
    found: dict[str, ast.expr] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    found[target.id] = node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
            found[node.target.id] = node.value
    return found


def _case_decorators(tree: ast.Module) -> list[tuple[str, tuple[str, ...]]]:
    """(case id, scenario names) of every ``@case(...)`` decorator, nested functions included."""
    found = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for decorator in node.decorator_list:
                if (isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Name)
                        and decorator.func.id == "case"):
                    found.append((ast.literal_eval(decorator.args[0]), tuple(ast.literal_eval(decorator.args[1]))))
    return found


def _string(node) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def test_the_case_ids_of_the_evaluators_are_the_catalogue_ids() -> None:
    """cases.py read with ast: the ids of the ``@case`` decorators and of ``CAMPAIGN_CASES`` (the cases that
    evaluate_campaign.py judges from the runs of a campaign) are disjoint and together the catalogue's ids, and
    evaluate_campaign.py names each campaign case.

    Cannot see: whether a decorated function judges the case it names, or which function of evaluate_campaign.py
    judges a campaign case; a case registered in any other way than these two.
    """
    tree = _module("cases.py")
    decorated = [vc for vc, _ in _case_decorators(tree)]
    assert len(decorated) == len(set(decorated)), "a case id is decorated twice"
    campaign_node = _assignments(tree).get("CAMPAIGN_CASES")
    assert campaign_node is not None, "cases.py declares no CAMPAIGN_CASES"
    campaign = list(ast.literal_eval(campaign_node))
    assert set(decorated).isdisjoint(campaign), set(decorated) & set(campaign)
    assert sorted(decorated + campaign) == [case["id"] for case in _catalogue()["cases"]]
    named = {_string(node) for node in ast.walk(_module("evaluate_campaign.py"))}
    assert set(campaign) <= named, set(campaign) - named


