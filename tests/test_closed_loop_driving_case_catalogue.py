def test_check_repo_runs_the_real_catalogue_gate_and_passes() -> None:
    """The pass-through spy: every other gate passes and the real catalogue gate runs once on the repository root
    and passes, so ``check_repo.main()`` returns 0.

    Cannot see: the gate's own messages (the check-mode test above reads them).
    """
    check_repo = _check_repo()
    original = check_repo.generate_driving_case_catalogue.run_check_errors
    calls = []

    def spy(root=None):
        calls.append(root)
        return original(root)

    gate = mock.patch.object(check_repo.generate_driving_case_catalogue, "run_check_errors", side_effect=spy)
    assert _run_check_repo(gate) == 0
    assert calls == [ROOT]


